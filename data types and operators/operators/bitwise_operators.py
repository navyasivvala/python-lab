# Program: Bitwise Operators

p = 12
q = 10

print("Binary of p:", bin(p))
print("Binary of q:", bin(q))

print("p & q :", p & q)
print("p | q :", p | q)
print("p ^ q :", p ^ q)
print("~p    :", ~p)
print("p << 2:", p << 2)
print("p >> 2:", p >> 2)

# Output:
# Binary of p: 0b1100
# Binary of q: 0b1010
# p & q : 8
# p | q : 14
# p ^ q : 6
# ~p    : -13
# p << 2: 48
# p >> 2: 3