m = int(input("Enter m: "))
n = int(input("Enter n: "))

print("m == n:", m == n)
print("m != n:", m != n)
print("m > n :", m > n)
print("m < n :", m < n)
print("m >= n:", m >= n)
print("m <= n:", m <= n)

