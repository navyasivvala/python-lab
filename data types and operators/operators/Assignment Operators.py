score = 50

print("Initial score:", score)

score += 10
print("After += 10:", score)

score -= 5
print("After -= 5:", score)

score *= 2
print("After *= 2:", score)

score /= 5
print("After /= 5:", score)

score //= 3
print("After //= 3:", score)

score %= 4
print("After %= 4:", score)

score **= 2
print("After **= 2:", score)

# Output:
# Initial score: 50
# After += 10: 60
# After -= 5: 55
# After *= 2: 110
# After /= 5: 22.0
# After //= 3: 7.0
# After %= 4: 3.0
# After **= 2: 9.0