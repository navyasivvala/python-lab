# Store first name and last name in string variables
first = "Navya"
last = "Sivvala"

# Concatenate first name and last name with a space
full_name = first + " " + last

# Print the full name in uppercase
print(full_name.upper())

# Print the full name in lowercase
print(full_name.lower())

# Print the full name in title case
print(full_name.title())

# Print the length of the full name
print(len(full_name))

# Print the first and last characters of the full name
print(full_name[0], full_name[-1])

# Output:
# NAVYA SIVVALA
# navya sivvala
