# Declare two boolean variables
is_raining = True
has_umbrella = False

# Print the type of the boolean variables
print(type(is_raining))
print(type(has_umbrella))

# Print the result of logical AND operation
print(is_raining and has_umbrella)

# Print the result of logical OR operation
print(is_raining or has_umbrella)

# Print the result of logical NOT operation
print(not is_raining)

# Verify that bool is a subtype of int
print(True + True)
print(False * 5)

